def localized_agent_table(rows: list[dict]) -> dict:
    """Merge the code-generated agent table with the Russian overlay."""
    agents = []
    for r in rows:
        ru = AGENTS_RU.get(r["agent"], {})
        tools = [{"name": k, "en": v, "ru": ru.get("tools", {}).get(k, "")} for k, v in r["tools"].items()
                 if k != "(none)"]
        agents.append({**{k: v for k, v in ru.items() if k != "tools"}, "name": r["agent"], "role_en": r["role"],
                       "done_en": r["done_when"], "tools": tools})
    return {"agents": agents, "protocol": PROTOCOL_RU, "requirements": REQUIREMENTS_RU}
