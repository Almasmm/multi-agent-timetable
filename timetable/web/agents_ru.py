def service_agent_table() -> list[dict]:
    """Russian spec of the 24/7 service agents (tool names are checked against the code in tests)."""
    from ..service.agents import SERVICE_AGENT_CLASSES
    from ..service.autopilot import Autopilot

    code = {cls.name: cls for cls in SERVICE_AGENT_CLASSES}
    out = []
    for a in SERVICE_RU:
        cls = code.get(a["name"])
        en = {}
        if cls is not None:
            dummy = cls.__new__(cls)
            dummy.tools = {}
            cls.register_tools(dummy)
            en = {t.name: t.description for t in dummy.tools.values()}
        role_en = cls.role if cls else Autopilot.role
        out.append({**{k: v for k, v in a.items() if k != "tools"}, "role_en": role_en,
                    "tools": [{"name": k, "en": en.get(k, ""), "ru": v} for k, v in a["tools"].items()]})
    return out


def localized_agent_table(rows: list[dict]) -> dict:
    """Merge the code-generated agent table with the Russian overlay."""
    agents = []
    for r in rows:
        ru = AGENTS_RU.get(r["agent"], {})
        tools = [{"name": k, "en": v, "ru": ru.get("tools", {}).get(k, "")} for k, v in r["tools"].items()
                 if k != "(none)"]
        agents.append({**{k: v for k, v in ru.items() if k != "tools"}, "name": r["agent"], "role_en": r["role"],
                       "done_en": r["done_when"], "tools": tools})
    return {"agents": agents, "protocol": PROTOCOL_RU, "requirements": REQUIREMENTS_RU}
